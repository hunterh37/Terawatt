import fs from 'node:fs';
const [,, inPath, outPath, nArg] = process.argv;
const gj = JSON.parse(fs.readFileSync(inPath, 'utf8'));
const polys = [];
for (const f of gj.features) {
  const g = f.geometry;
  const list = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const p of list) {
    const ring = p[0];
    let minX = 180, maxX = -180, minY = 90, maxY = -90;
    for (const [x, y] of ring) { if (x < minX) minX = x; if (x > maxX) maxX = x; if (y < minY) minY = y; if (y > maxY) maxY = y; }
    polys.push({ rings: p, bbox: [minX, minY, maxX, maxY] });
  }
}
function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function onLand(lon, lat) {
  for (const p of polys) {
    const b = p.bbox;
    if (lon < b[0] || lon > b[2] || lat < b[1] || lat > b[3]) continue;
    if (inRing(lon, lat, p.rings[0])) {
      let hole = false;
      for (let k = 1; k < p.rings.length; k++) if (inRing(lon, lat, p.rings[k])) { hole = true; break; }
      if (!hole) return true;
    }
  }
  return false;
}
const N = Number(nArg || 16000), dots = [];
const golden = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2, r = Math.sqrt(1 - y * y), th = golden * i;
  const lat = Math.asin(y) * 180 / Math.PI;
  let lon = (Math.atan2(r * Math.sin(th), r * Math.cos(th)) * 180) / Math.PI;
  if (lat < -60) continue; // skip Antarctica for a cleaner globe
  if (onLand(lon, lat)) dots.push([Math.round(lat * 10) / 10, Math.round(lon * 10) / 10]);
}
const header = `// Land dots for the fleet globe: ${dots.length} points from a ${N}-point Fibonacci sphere,\n// kept where they fall on land in Natural Earth 1:110m land polygons (public domain,\n// https://www.naturalearthdata.com). Antarctica omitted. Generated by scripts/land-dots.mjs.\n`;
fs.writeFileSync(outPath, header + 'export const LAND_DOTS = ' + JSON.stringify(dots) + ';\n');
