// Regenerates src/data/fixture-metrics.js from the engine (the start preset). Run: node scripts/make-fixture.mjs
import { writeFileSync } from 'node:fs';
import { PRESETS, derive } from '../src/engine/engine.js';
import { SENTIMENT } from '../src/data/sentiment.js';

const scenario = PRESETS['fit-grid'].make();
const metrics = derive(scenario, { sentiment: SENTIMENT });
const out = `// GENERATED by scripts/make-fixture.mjs from the 'fit-grid' preset. Builders read this to see the exact
// shape and scale of engine output; the app itself always calls the engine.
export const FIXTURE_SCENARIO = ${JSON.stringify(scenario, null, 1)};
export const FIXTURE_METRICS = ${JSON.stringify(metrics, null, 1)};
`;
writeFileSync(new URL('../src/data/fixture-metrics.js', import.meta.url), out);
console.log('wrote fixture', out.length, 'bytes; firstFailing', metrics.firstFailing && metrics.firstFailing.id);
